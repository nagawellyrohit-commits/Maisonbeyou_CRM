export function getLocationBranding(location) {
  let saved = location?.branding_config;
  if (typeof saved === 'string') {
    try { saved = JSON.parse(saved); } catch { saved = {}; }
  }
  if (!saved || typeof saved !== 'object' || Array.isArray(saved)) saved = {};
  return {
    ...DEFAULT_LOCATION_BRANDING,
    ...saved,
    brand_name: saved.brand_name || location?.name || DEFAULT_LOCATION_BRANDING.brand_name
  };
}

